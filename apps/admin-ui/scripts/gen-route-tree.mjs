import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
// router-generator is a transitive dep of router-plugin and not declared
// directly in package.json. Resolve through router-plugin to find it.
const routerPluginPkg = require.resolve("@tanstack/router-plugin/package.json");
const routerPluginNm = path.dirname(routerPluginPkg);
const generatorEntry = path.join(
  routerPluginNm,
  "..",
  "router-generator",
  "dist",
  "esm",
  "index.js"
);

const { Generator, getConfig } = await import(generatorEntry);

const root = process.cwd();
const config = getConfig(
  {
    routesDirectory: "./src/routes",
    generatedRouteTree: "./src/routeTree.gen.ts",
    quoteStyle: "double",
    semicolons: false,
    disableLogging: true,
    routeTreeFileHeader: ["// This file is auto-generated by TanStack Router"],
    routeTreeFileFooter: [],
    autoCodeSplitting: true,
  },
  root
);

const generator = new Generator({ config, root });
await generator.run();
